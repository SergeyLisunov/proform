-- 109_audit_action_clearance_override.sql
--
-- Колонка public.audit_logs.action имеет тип enum public.audit_action:
--   create | update | delete | login | logout | role_change |
--   privacy_change | assign_athlete
--
-- Три маршрута писали в неё значения, которых в enum нет. Postgres отвечает
-- 22P02 (invalid input value for enum), и дальше поведение расходится:
--
--   • /api/admin/users/role      — 'admin.user.role_changed'
--     Результат insert не проверялся: маршрут отвечал 200, а запись в
--     журнал не появлялась. Требование «смена роли логируется» не
--     выполнялось молча.
--   • /api/org/members/role      — 'org_member_role_change'
--     То же самое: смена роли участника клуба не попадала в журнал.
--   • /api/clearance/override    — 'clearance_override'
--     Здесь ошибка ПРОВЕРЯЕТСЯ и возвращается как 500 'audit_failed'.
--     То есть обход медицинского допуска не просто не логировался —
--     маршрут падал на КАЖДОМ вызове, функция была мертва целиком.
--
-- Две первых точки переведены на существующее значение 'role_change'
-- (детализация ушла в payload). Третьей нужен собственный ярлык: обход
-- врачебного ограничения — событие для разбора, и в журнале администратора
-- (экран /admin) оно должно читаться как таковое, а не как безликое 'update'.
--
-- ADD VALUE идемпотентен (IF NOT EXISTS) и аддитивен: существующие строки и
-- читатели не затрагиваются. Новое значение нельзя использовать в той же
-- транзакции, где оно добавлено, — здесь оно только объявляется.
--
-- Регрессия: lib/db/audit-action-vocabulary.test.ts — сторож сверяет все
-- литералы action, которые код пишет в audit_logs, со словарём enum.
-- ──────────────────────────────────────────────────────────────────────────

ALTER TYPE public.audit_action ADD VALUE IF NOT EXISTS 'clearance_override';

NOTIFY pgrst, 'reload schema';
