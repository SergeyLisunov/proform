/**
 * Prompt Registry — системные инструкции ролевых ассистентов Sporteo.
 *
 * SERVER-ONLY: этот модуль импортируется только из route handlers /
 * серверных сервисов. Промпты никогда не попадают во frontend bundle и
 * не возвращаются клиенту; в БД хранится только версия (snapshot в
 * ai_conversations.prompt_version).
 *
 * Anti-injection: системная политика стоит выше любого пользовательского
 * текста; контент пользователя и данные из БД помечаются как недоверенные
 * данные, а не инструкции. Модель не имеет tool calls — ассистент только
 * советует, любые изменения данных пользователь выполняет сам в интерфейсе
 * (подтверждение действий по построению).
 */
